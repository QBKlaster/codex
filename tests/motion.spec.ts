import { test, expect } from '@playwright/test'

test('scroll reveals finish and newly filtered cards remain usable', async ({ page }) => {
  await page.goto('/')
  const cards = page.locator('#mahsulotlar .product-card')
  await expect(cards.first()).toHaveAttribute('data-motion-reveal', 'pending')
  await expect(cards.first()).toHaveCSS('opacity', '0')
  await cards.first().scrollIntoViewIfNeeded()
  await expect(cards.first()).toHaveAttribute('data-motion-reveal', 'visible')
  await expect.poll(() => cards.first().evaluate(element => element.getAnimations().filter(animation => animation.playState === 'running' || animation.playState === 'pending').length)).toBe(0)
  await expect(cards.first()).toHaveCSS('opacity', '1')
  await expect.poll(() => page.evaluate(() => Number(document.documentElement.style.getPropertyValue('--page-progress')))).toBeGreaterThan(0)

  const catalog = page.locator('#mahsulotlar')
  await catalog.getByRole('button', { name: 'Bloklar', exact: true }).click()
  await expect(cards).toHaveCount(1)
  await catalog.getByRole('button', { name: /^Barchasi/ }).click()
  await expect(cards).toHaveCount(3)
  for (const card of await cards.all()) {
    await expect(card).toHaveAttribute('data-motion-reveal', 'visible')
    await expect(card).toHaveCSS('opacity', '1')
  }
  await catalog.getByRole('button', { name: 'Temir-beton mahsulotlari haqida batafsil' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
})

test('reduced motion can change live and leaves no hidden content or active animation', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.contact-card')).toHaveAttribute('data-motion-reveal', 'pending')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('html')).not.toHaveClass(/motion-ready/)
  await expect(page.locator('[data-motion-reveal="pending"]')).toHaveCount(0)
  await expect(page.locator('.contact-card')).toHaveCSS('opacity', '1')
  await expect.poll(() => page.evaluate(() => document.getAnimations().filter(animation => animation.playState === 'running' || animation.playState === 'pending').length)).toBe(0)

  await page.reload()
  await expect(page.locator('html')).not.toHaveClass(/motion-ready/)
  await expect(page.locator('[data-motion-reveal="pending"]')).toHaveCount(0)
  await expect(page.locator('.hero-line > span').first()).toHaveCSS('opacity', '1')
  await expect(page.locator('.product-card').first()).toHaveCSS('opacity', '1')
  await expect(page.locator('.contact-card')).toHaveCSS('opacity', '1')
})

test('calculator announces exact targets and handles rapid animated updates', async ({ page }) => {
  await page.goto('/')
  const calculator = page.locator('#kalkulyator')
  await calculator.scrollIntoViewIfNeeded()
  const length = calculator.getByRole('spinbutton', { name: /Uzunligi/ })
  const status = calculator.getByRole('status')
  const number = calculator.locator('.calculator-volume > span').first()
  await length.fill('20')
  await expect(status).toContainText('35.20 m³')
  await length.fill('30')
  await length.fill('5')
  await expect(status).toContainText('8.80 m³')
  await expect(number).toHaveText('8.80')
  await length.fill('15')
  await expect(status).toContainText('26.40 m³')
  await calculator.getByRole('button', { name: 'Shu hajmga taklif olish' }).click()
  await expect(page.getByRole('dialog').getByRole('textbox', { name: 'Loyihangiz haqida' })).toHaveValue(/26.40 m³/)
  await page.keyboard.press('Escape')
  await length.fill('0')
  await expect(number).toHaveText('—')
  await expect(calculator.getByRole('button', { name: 'Shu hajmga taklif olish' })).toBeDisabled()
})

test.describe('touch motion', () => {
  test.use({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
  test('touch pointer movement does not tilt cards or shift the hero image', async ({ page }) => {
    await page.goto('/')
    await page.locator('.hero').dispatchEvent('pointermove', { pointerType: 'touch', clientX: 200, clientY: 200 })
    const card = page.locator('.product-card').first()
    await card.scrollIntoViewIfNeeded()
    await expect(card).toHaveAttribute('data-motion-reveal', 'visible')
    await card.dispatchEvent('pointermove', { pointerType: 'touch', clientX: 50, clientY: 150 })
    expect(await card.evaluate(element => element.style.getPropertyValue('--tilt-x'))).toBe('')
    expect(await card.evaluate(element => element.style.getPropertyValue('--tilt-y'))).toBe('')
    expect(await page.locator('.hero').evaluate(element => element.style.getPropertyValue('--hero-x'))).toBe('')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
    await card.getByRole('button', { name: 'Tayyor beton haqida batafsil' }).tap()
    await expect(page.getByRole('dialog')).toBeVisible()
  })
})
